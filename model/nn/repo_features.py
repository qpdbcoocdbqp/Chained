"""
repo_features.py — Per-repo features for the neural file scorer.

The XGBoost scorer sees one path at a time.  The gold lists in
model/tmp/gold/ show that what makes a file worth reading is mostly relative
to the rest of the repo (see model/nn/README.md for the numbers):

  mentions   curl's docs/cmdline-opts/ has 298 pages with the same path
             features; the gold ones (data.md, header.md, ...) are the options
             the docs keep mentioning.  Same for docs/libcurl/curl_easy_*.md
             and go-redis' options.go / pipeline.go.
  hub links  20 of llama.cpp's 50 gold files are linked from the root README,
             and 20 of the 28 files it links are gold.  vite's guide pages
             are linked from the docs site navigation (.vitepress/config.ts).
  siblings   gold files are a few picks among many similar siblings, so how a
             file compares to its directory matters more than its absolute
             numbers.
  content    user docs are full of commands and code blocks; API files
             declare many exported symbols; examples have a main().
  path       the vocabulary of user material (install, quickstart, guide,
             include, client, example, simple ...), as tokens the model embeds.

RepoFeatures(root, files).build() reads the repo once and returns, for every
file: its path tokens, the NUMERIC_COLUMNS vector and its parent / top-level
directory groups, which the network pools over (model/nn/net.py).
"""
import math
import os
import re
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from model.file_features import extract_features

# Bump whenever tokens or NUMERIC_COLUMNS change: cached features are keyed on
# it and a model trained on another version is rejected.
FEATURE_VERSION = "nn-v1"

READ_BYTES = 64 * 1024          # content statistics look at this much of a file
SCAN_BYTES = 32 * 1024          # mention scan looks at this much of a file
STUB_BYTES = 300                # smaller files are usually placeholders

DOC_EXTS = {".md", ".mdx", ".rst", ".txt", ".adoc"}
# Doc-site directories that collector.Repo leaves out (dot dirs) but whose
# navigation config links the user docs
DOC_SITE_DIRS = {".vitepress", ".vuepress", ".docusaurus"}
SKIP_DIRS = {".git", "node_modules", "__pycache__", "dist", "build", ".venv", "venv"}
DOCS_ROOTS = {"docs", "doc", "documentation", "website"}
# Navigation files of documentation sites: what they link is the user docs
NAV_NAMES = re.compile(r"^(mkdocs\.ya?ml|docs\.json|mint\.json|summary\.md|_sidebar\.md|_toc\.ya?ml|"
                       r"sidebars?\.(js|ts|json)|config\.(js|ts|mts|mjs))$", re.I)

_PATH_TOKEN = re.compile(r"[A-Za-z0-9_./-]+")
_WORD = re.compile(r"[a-z_][a-z0-9_-]{2,}")
_SPLIT = re.compile(r"[-_.\s]+")
_CAMEL = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+")

_FENCE = re.compile(r"^\s*(```|~~~)", re.M)
_PROMPT = re.compile(r"^\s*\$ \S", re.M)
_HEADING = re.compile(r"^#{1,6}\s", re.M)
_MD_LINK = re.compile(r"\]\(")
_INSTALL = re.compile(r"\b(pip3? install|npm (install|i|create)|yarn (add|create)|pnpm (add|create)|npx |"
                      r"go (get|install)|cargo (add|install)|brew install|apt(-get)? install|"
                      r"docker (run|pull|compose)|cmake -B|make install|winget install|"
                      r"curl -fsSL|conda install|nix profile)", re.I)
_CLI_FLAG = re.compile(r"(?<![\w-])--[a-z][\w-]+")
_EXPORTED = re.compile(
    r"^(func (\([^)]*\)\s*)?[A-Z]|type [A-Z]"              # Go
    r"|(async )?def [a-zA-Z]|class [A-Za-z]"               # Python (top level)
    r"|\s*[A-Z][A-Z0-9]*_(API|EXTERN)\b"                  # C / C++ export macros
    r"|export )", re.M)                                     # TypeScript / JavaScript
_MAIN = re.compile(r"func main\(|\bint main\(|__name__ == .__main__.")
_GO_EXAMPLE = re.compile(r"^func Example", re.M)
_GENERATED = re.compile(r"do not edit|generated by|auto-?generated", re.I)

# Columns of extract_features() fed to the network (as is, log1p for counts)
PATH_FLAGS = ["ext_group_code", "ext_group_config", "ext_group_doc", "ext_group_data",
              "ext_group_test", "ext_group_other", "in_docs", "in_examples", "in_src",
              "in_internal", "in_tests", "in_devops", "in_ignored", "in_util_dir", "in_ops",
              "in_maintainer_docs", "is_public_api", "is_cli_entry", "is_user_config",
              "is_dev_config", "is_readme", "is_test_file", "is_example_file",
              "is_private_module", "is_internal_name", "is_public_api_name", "rule_score"]
NUMERIC_COLUMNS = PATH_FLAGS + [
    # structure
    "depth", "src_depth", "is_root", "stem_is_parent", "go_example_test",
    "dir_files", "dir_same_ext", "dir_same_ext_frac", "dir_subdirs", "top_share", "repo_files",
    # content
    "size", "lines", "unreadable", "generated", "stub", "fences", "prompts", "headings",
    "md_links", "install_cmds", "cli_flags", "exported", "has_main", "go_examples",
    # mentions
    "hub_link", "path_mentions", "stem_user_mentions", "stem_mentions", "ref", "example_ref",
    # compared with siblings of the same extension in the same directory
    "sib_stem_user_pct", "sib_stem_pct", "sib_size_pct", "sib_path_pct",
]


def repo_stem(repo_name: str) -> str:
    """The distinctive part of a repo name (llama.cpp -> llama, go-redis ->
    redis), masked in path tokens so the model cannot learn repo names."""
    parts = [p for p in re.split(r"[-_.]", repo_name.lower()) if len(p) >= 4]
    return max(parts, key=len) if parts else repo_name.lower()


def split_name(name: str) -> list[str]:
    """'TheArtOfHttpScripting' -> the art of http scripting,
    'curl_easy-setopt' -> curl easy setopt."""
    out = []
    for piece in _SPLIT.split(name):
        out += [t.lower() for t in _CAMEL.findall(piece)] or ([piece.lower()] if piece else [])
    return out


def path_tokens(rel: str, mask: str) -> list[str]:
    """Role-prefixed path tokens: d: any directory, p: parent directory,
    t: top-level directory, s: stem word, n: whole stem, x: extension."""
    parts = rel.split("/")
    dirs, name = parts[:-1], parts[-1]
    stem, ext = os.path.splitext(name)
    if not stem:                      # dot files: .env.example
        stem, ext = name, ""

    def masked(t: str) -> str:
        return t.replace(mask, "<repo>") if mask and len(t) > 0 else t

    toks = [f"x:{ext.lower() or '<none>'}", f"n:{masked(stem.lower())}"]
    toks += [f"s:{masked(t)}" for t in split_name(stem)]
    for i, d in enumerate(dirs):
        words = [masked(t) for t in split_name(d)]
        toks += [f"d:{w}" for w in words]
        if i == len(dirs) - 1:
            toks += [f"p:{w}" for w in words]
        if i == 0:
            toks.append(f"t:{masked(d.lower())}")
    if not dirs:
        toks.append("t:<root>")
    return toks


@dataclass
class RepoTensors:
    """Features of every file of one repo, in `files` order."""
    files: list[str]            # "/"-separated relative paths
    tokens: list[list[str]]
    numeric: np.ndarray         # [n_files, len(NUMERIC_COLUMNS)] float32
    parent: np.ndarray          # [n_files] parent directory group id
    top: np.ndarray             # [n_files] top-level directory group id


class RepoFeatures:
    """Reads a checkout once and computes the features of `files` (relative
    paths, as collector.Repo.files lists them)."""

    def __init__(self, root: str | Path, files: list[str], repo_name: str | None = None):
        self.root = Path(root)
        self.files = [f.replace(os.sep, "/") for f in files]
        self.mask = repo_stem(repo_name or self.root.name)

    # -- reading ---------------------------------------------------------------

    def _read(self, rel: str) -> str | None:
        try:
            with open(self.root / rel, "rb") as f:
                data = f.read(READ_BYTES)
        except OSError:
            return None
        if b"\x00" in data[:4096]:
            return None
        return data.decode("utf-8", errors="ignore").replace("\r\n", "\n")

    def _doc_site_files(self) -> list[str]:
        """Files under doc-site dot dirs (docs/.vitepress/config.ts), which
        are not in `files` but link the user docs."""
        out = []
        for dirpath, dirnames, filenames in os.walk(self.root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS
                           and (not d.startswith(".") or d in DOC_SITE_DIRS)]
            rel_dir = os.path.relpath(dirpath, self.root).replace(os.sep, "/")
            if any(p in DOC_SITE_DIRS for p in rel_dir.split("/")):
                out += [f"{rel_dir}/{f}" for f in filenames if NAV_NAMES.match(f)]
        return out

    @staticmethod
    def _is_hub(rel: str) -> bool:
        """Entry-point documents whose links point at user material: the root
        README, the README / index of the docs root, docs-site navigation."""
        parts = rel.lower().split("/")
        name = parts[-1]
        if len(parts) == 1:
            return name.startswith(("readme", "mkdocs."))
        if any(p in DOC_SITE_DIRS for p in parts[:-1]):
            return True
        if parts[0] in DOCS_ROOTS and len(parts) == 2:
            return name.startswith(("readme", "index", "summary")) or bool(NAV_NAMES.match(name))
        return False

    @staticmethod
    def _is_user_text(rel: str, feats: dict) -> bool:
        """Text a user reads: docs, READMEs and examples."""
        return bool(feats["ext_group_doc"] or feats["is_readme"] or feats["in_examples"]
                    or feats["is_example_file"] or rel.endswith("example_test.go"))

    # -- keys a file is mentioned by ----------------------------------------------

    @staticmethod
    def _keys(rel: str) -> list[str]:
        """Ways other files refer to `rel`: docs/build.md, docs/build,
        cmdline-opts/data, guide/cli (vitepress), quickstart (mintlify)."""
        rel = rel.lower()
        parts = rel.split("/")
        noext = rel.rsplit(".", 1)[0] if "." in parts[-1] else rel
        nparts = noext.split("/")
        keys = {rel, noext}
        if len(parts) >= 2:
            keys.add("/".join(parts[-2:]))
            keys.add("/".join(nparts[-2:]))
        if len(parts) >= 2 and parts[0] in DOCS_ROOTS:
            keys.add("/".join(nparts[1:]))
        if len(parts) == 1 and "." in parts[0]:
            keys.add(parts[0])                  # options.go at the root
        return [k for k in keys if len(k) >= 3]

    # -- build -------------------------------------------------------------------

    def build(self) -> RepoTensors:
        from model.ref_counts import build_ref_counts

        files, n = self.files, len(self.files)
        feats = [extract_features(f) for f in files]
        texts = [self._read(f) for f in files]
        extra = self._doc_site_files()
        extra_texts = [self._read(f) for f in extra]

        # Which file each key may refer to; a key shared by k files is ambiguous
        key_files: dict[str, list[int]] = defaultdict(list)
        file_keys = [self._keys(f) for f in files]
        for i, keys in enumerate(file_keys):
            for k in keys:
                key_files[k].append(i)
        stems = [os.path.splitext(f.split("/")[-1])[0].lower() for f in files]
        stem_count = Counter(stems)

        # Mention scan: path keys and words in each text
        key_df: Counter = Counter()          # files mentioning a key
        hub_keys: set[str] = set()
        word_df: Counter = Counter()         # files containing a word
        user_word_df: Counter = Counter()    # user docs / examples containing a word
        own_words: list[set[str]] = [set() for _ in range(n)]
        corpus = [(f, t, i) for i, (f, t) in enumerate(zip(files, texts))] + \
                 [(f, t, -1) for f, t in zip(extra, extra_texts)]
        for rel, text, i in corpus:
            if not text:
                continue
            scan = text[:SCAN_BYTES]
            mentioned = set()
            for tok in _PATH_TOKEN.findall(scan):
                tok = tok.strip("./").lower()
                if not tok:
                    continue
                segs = tok.split("/")
                for j in range(len(segs)):
                    suffix = "/".join(segs[j:])
                    if suffix in key_files:
                        mentioned.add(suffix)
            own = set(file_keys[i]) if i >= 0 else set()
            mentioned -= own
            key_df.update(mentioned)
            if self._is_hub(rel):
                hub_keys |= mentioned
            words = set(_WORD.findall(scan.lower()))
            word_df.update(words)
            if i >= 0:
                own_words[i] = words
                if self._is_user_text(rel, feats[i]):
                    user_word_df.update(words)
            elif self._is_hub(rel):
                user_word_df.update(words)

        refs_ex: dict[str, int] = {}
        native = [f.replace("/", os.sep) for f in files]
        refs = build_ref_counts(str(self.root), native, example_counts=refs_ex)

        parent_of = [f.rsplit("/", 1)[0] if "/" in f else "" for f in files]
        top_of = [f.split("/", 1)[0] if "/" in f else "" for f in files]
        exts = [os.path.splitext(f)[1].lower() for f in files]
        dir_files = Counter(parent_of)
        dir_ext = Counter(zip(parent_of, exts))
        subdirs = Counter(p.rsplit("/", 1)[0] if "/" in p else "" for p in set(parent_of) if p)
        top_files = Counter(top_of)

        rows = []
        for i, rel in enumerate(files):
            f, text = feats[i], texts[i]
            stem = stems[i]
            parts = rel.split("/")
            try:
                size = (self.root / rel).stat().st_size
            except OSError:
                size = 0
            is_doc = exts[i] in DOC_EXTS
            row = {c: float(f[c]) for c in PATH_FLAGS}
            row.update(
                depth=math.log1p(f["depth"]), src_depth=math.log1p(f["src_depth"]),
                is_root=float(len(parts) == 1),
                stem_is_parent=float(len(parts) > 1 and stem == parts[-2].lower()),
                go_example_test=float(rel.endswith("example_test.go")),
                dir_files=math.log1p(dir_files[parent_of[i]]),
                dir_same_ext=math.log1p(dir_ext[(parent_of[i], exts[i])]),
                dir_same_ext_frac=dir_ext[(parent_of[i], exts[i])] / dir_files[parent_of[i]],
                dir_subdirs=math.log1p(subdirs[parent_of[i]]),
                top_share=top_files[top_of[i]] / n if top_of[i] else 0.0,
                repo_files=math.log1p(n) / 10,
                size=math.log1p(size) / 10,
                unreadable=float(text is None),
                stub=float(size < STUB_BYTES),
            )
            t = text or ""
            row.update(
                lines=math.log1p(t.count("\n")) / 10,
                generated=float(bool(_GENERATED.search(t[:1024]))),
                fences=math.log1p(len(_FENCE.findall(t)) // 2),
                prompts=math.log1p(len(_PROMPT.findall(t))),
                headings=math.log1p(len(_HEADING.findall(t))) if is_doc else 0.0,
                md_links=math.log1p(len(_MD_LINK.findall(t))),
                install_cmds=math.log1p(len(_INSTALL.findall(t))),
                cli_flags=math.log1p(len(_CLI_FLAG.findall(t))),
                exported=math.log1p(len(_EXPORTED.findall(t))) if not is_doc else 0.0,
                has_main=float(bool(_MAIN.search(t))),
                go_examples=math.log1p(len(_GO_EXAMPLE.findall(t))),
            )
            # mentions: a key shared by k files gives each 1/k
            row["hub_link"] = float(any(k in hub_keys and len(key_files[k]) == 1 for k in file_keys[i]))
            row["path_mentions"] = math.log1p(max([key_df[k] / len(key_files[k]) for k in file_keys[i]] + [0]))
            amb = stem_count[stem]
            self_hit = 1 if stem in own_words[i] else 0
            user_self = self_hit if self._is_user_text(rel, f) else 0
            ok = len(stem) >= 3
            row["stem_user_mentions"] = math.log1p(max(0, user_word_df[stem] - user_self) / amb) if ok else 0.0
            row["stem_mentions"] = math.log1p(max(0, word_df[stem] - self_hit) / amb) if ok else 0.0
            native_rel = native[i]
            row["ref"] = math.log1p(refs.get(native_rel, 0))
            row["example_ref"] = math.log1p(refs_ex.get(native_rel, 0))
            rows.append(row)

        # Percentile among siblings with the same extension, centred on 0;
        # files without such siblings get 0
        groups: dict[tuple, list[int]] = defaultdict(list)
        for i in range(n):
            groups[(parent_of[i], exts[i])].append(i)
        for col, src in (("sib_stem_user_pct", "stem_user_mentions"), ("sib_stem_pct", "stem_mentions"),
                         ("sib_size_pct", "size"), ("sib_path_pct", "path_mentions")):
            for idx in groups.values():
                if len(idx) == 1:
                    rows[idx[0]][col] = 0.0
                    continue
                vals = np.array([rows[i][src] for i in idx])
                ranks = _average_ranks(vals)
                for i, r in zip(idx, ranks):
                    rows[i][col] = r / (len(idx) - 1) - 0.5

        numeric = np.array([[row[c] for c in NUMERIC_COLUMNS] for row in rows], np.float32)
        return RepoTensors(
            files=files,
            tokens=[path_tokens(f, self.mask) for f in files],
            numeric=numeric,
            parent=_group_ids(parent_of),
            top=_group_ids(top_of),
        )


def _average_ranks(vals: np.ndarray) -> np.ndarray:
    """0-based ranks, ties get their average rank."""
    order = vals.argsort(kind="stable")
    ranks = np.empty(len(vals))
    ranks[order] = np.arange(len(vals))
    for v in np.unique(vals):
        tie = vals == v
        if tie.sum() > 1:
            ranks[tie] = ranks[tie].mean()
    return ranks


def _group_ids(keys: list[str]) -> np.ndarray:
    ids: dict[str, int] = {}
    return np.array([ids.setdefault(k, len(ids)) for k in keys], np.int64)
